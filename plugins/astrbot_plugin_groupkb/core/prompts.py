import json
import re

EXTRACT_SYSTEM = """你在给一个 QQ 群整理知识库。给你这个群某天的一段聊天记录，每行「时间 代号：内容」，代号是谁见【代号】；还有知识库里已经记了的东西。从这段里找出三样：

1. nicknames：群友在群名片以外被叫的外号。要有聊天里的证据：有人这样叫他、@他的时候这样称呼他、他被这样叫时接了话。
   - 只记专属的外号。「哥」「老板」「大佬」「宝宝」「老师」「兄弟」「群主」「管理」这种谁都能叫的称呼不记
   - 群名片本身、群名片的一部分不记；已经记过的不记；拿不准是在叫谁的不记
   - 说的是明星、角色、主播、群外的人，不记
2. notes：这个群特有、会反复用到的黑话、梗、规矩，新来的人看不懂的那种，一条一句写清楚是什么意思，30 字以内，比如「绿帽：指群管理员」。宁缺毋滥，大多数时候应该是空的：
   - 某人某天的一次性玩笑、调侃，放进 events，不算黑话
   - 机器人的功能、指令（搜烧鸡、猜题、杀炫区怎么用）不算
   - 普通的网络用语不算，已经有的不记
3. events：这段里有意思、值得留档的事，一件一句，40 字以内，写清是谁（用群名片）干了什么、群里什么反应。比如有人过生日、谁晒了什么被围攻、吵了一架、出了个新梗、机器人闹了什么笑话、玩猜题有谁连对。日常闲聊、刷屏、复读、单纯的问答不算；这段没什么事就给空列表。

规矩：notes 和 events 里提到人用【代号】里的群名片，不要写代号；不写涉黄的细节，不写真名、住址、学校、公司、手机号这类隐私，不骂人、不评价长相。

只输出一个 JSON 对象，不要输出别的：
{"nicknames": [{"who": "代号", "name": "外号", "why": "证据，引用原话"}], "notes": ["……"], "events": [{"time": "HH:MM", "text": "……"}]}"""

DIGEST_SYSTEM = """你在给一个 QQ 群写当天的留档。给你这天各段聊天里挑出来的事（可能有重复、有琐碎的），还有新发现的黑话、梗，以及知识库里已经有的黑话。

- events：挑最有意思、最值得以后翻出来看的，最多 {n} 件；同一件事合并成一件；按时间排；每件一句 40 字以内，开头写时间「HH:MM」，写清是谁干了什么。宁缺毋滥，平淡的一天可以只有一两件。
- notes：新发现的黑话、梗里，只留和已有的意思不重复、确实是这个群特有、以后还会反复用到的，最多 3 条，可以改得更简洁；一次性的玩笑、机器人的功能、普通网络用语都丢掉。大多数日子应该一条都不留。

规矩：不写涉黄的细节，不写真名、住址、学校、公司、手机号这类隐私，不骂人、不评价长相。

只输出一个 JSON 对象：{{"events": ["HH:MM ……"], "notes": ["……"]}}"""

FENCE = re.compile(r"^```(?:json)?\s*|\s*```$")


def parse_json(text: str) -> dict | None:
    """模型偶尔会包一层 ```json，或者在前后多说几句，取第一个 { 到最后一个 }。"""
    text = FENCE.sub("", (text or "").strip())
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end <= start:
        return None
    try:
        data = json.loads(text[start:end + 1])
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None
